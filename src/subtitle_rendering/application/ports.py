"""Injected local capabilities; application never imports concrete media adapters."""

from __future__ import annotations

from typing import Iterable, Protocol

from archive_core.interfaces import (
    RenderFontIdentityDTO, RenderFontSpecDTO, RenderMediaDTO, RenderProfileDTO,
    RenderStreamMappingDTO, RenderToolsDTO, SubtitlePlanDTO, SubtitleRenderPlanDTO,
)
from subtitle_rendering.domain.models import FontMeasurer


class RenderingArtifactStore(Protocol):
    def exists(self, path: str) -> bool: ...
    def read_bytes(self, path: str) -> bytes: ...
    def size(self, path: str) -> int: ...
    def sha256(self, path: str) -> str: ...
    def plan_staging(self, workspace: str) -> str: ...
    def create_staging(self, path: str) -> None: ...
    def stage_bytes(self, path: str, data: bytes) -> None: ...
    def publish(self, staged: str, target: str, *, overwrite: bool) -> None: ...


class RenderingFont(FontMeasurer, Protocol):
    identity: RenderFontIdentityDTO


class FontFactory(Protocol):
    def __call__(self, spec: RenderFontSpecDTO, texts: Iterable[str]) -> RenderingFont: ...


class AssCodec(Protocol):
    library_version: str

    def encode(self, plan: SubtitleRenderPlanDTO, source: SubtitlePlanDTO) -> bytes: ...
    def validate(self, data: bytes, plan: SubtitleRenderPlanDTO, source: SubtitlePlanDTO) -> None: ...


class MediaProbe(Protocol):
    def version(self) -> str: ...
    def probe(self, path: str) -> RenderMediaDTO: ...


class Renderer(Protocol):
    def tool_identity(self, *, pysubs2_version: str, ffprobe_version: str) -> RenderToolsDTO: ...
    def build_command(self, *, video_path: str, ass_path: str, fonts_dir: str, output_path: str,
                      profile: RenderProfileDTO, mapping: RenderStreamMappingDTO) -> tuple[str, ...]: ...
    def render(self, command: tuple[str, ...], *, cwd: str) -> object: ...


class Clock(Protocol):
    def now_utc(self) -> str: ...
